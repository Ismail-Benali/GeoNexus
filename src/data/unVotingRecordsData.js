/**
 * دالة استخراج سجل تصويت دولة معينة عبر كافة القرارات
 */
export function getCountryUnVotingRecord(countryId) {
  if (!countryId) return [];
  const normalized = countryId.toLowerCase();
  
  return UN_RESOLUTIONS_DATABASE.map((res) => {
    const voteData = res.countryVotes[normalized] || {
      vote: 'absent_or_not_recorded',
      voteAr: 'غير مسجل أو لم يشارك',
      noteAr: 'لم يسجل تصويت مباشر أو لم تكن الدولة عضواً في الهيئة المصوتة',
    };

    return {
      resolutionId: res.id,
      symbol: res.symbol,
      body: res.body,
      bodyAr: res.bodyAr,
      date: res.date,
      titleAr: res.titleAr,
      titleEn: res.titleEn,
      category: res.category,
      categoryAr: res.categoryAr,
      tally: res.tally,
      userCountryVote: voteData.vote,
      userCountryVoteAr: voteData.voteAr,
      userCountryNoteAr: voteData.noteAr,
      sourceUrl: res.sourceUrl,
    };
  });
}

/**
 * دالة إحصائيات عامة لسجلات الأمم المتحدة
 */
export function getUnVotingStats() {
  const totalResolutions = UN_RESOLUTIONS_DATABASE.length;
  const ungaCount = UN_RESOLUTIONS_DATABASE.filter((r) => r.body === 'unga').length;
  const unscCount = UN_RESOLUTIONS_DATABASE.filter((r) => r.body === 'unsc').length;

  return {
    totalResolutions,
    ungaCount,
    unscCount,
  };
}
