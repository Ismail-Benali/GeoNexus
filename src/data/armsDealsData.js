/**
 * دالة مساعدة للحصول على صفقات دولة معينة (سواء كانت مستوردة أو مصدرة)
 */
export function getCountryArmsDeals(countryId) {
  if (!countryId) return [];
  const normalized = countryId.toLowerCase();
  return ARMS_DEALS_DATABASE.filter(
    (deal) => deal.buyerId.toLowerCase() === normalized || deal.sellerId.toLowerCase() === normalized
  );
}

/**
 * دالة إحصائيات عامة لسوق السلاح
 */
export function getArmsDealsStats() {
  const totalValue = ARMS_DEALS_DATABASE.reduce((acc, curr) => acc + curr.valueNumberUsd, 0);
  const activeDealsCount = ARMS_DEALS_DATABASE.length;
  const categoriesCount = {
    air_force: ARMS_DEALS_DATABASE.filter((d) => d.category === 'air_force').length,
    air_defense: ARMS_DEALS_DATABASE.filter((d) => d.category === 'air_defense').length,
    naval: ARMS_DEALS_DATABASE.filter((d) => d.category === 'naval').length,
    land_forces: ARMS_DEALS_DATABASE.filter((d) => d.category === 'land_forces').length,
    drones: ARMS_DEALS_DATABASE.filter((d) => d.category === 'drones').length,
    other: ARMS_DEALS_DATABASE.filter((d) => !['air_force', 'air_defense', 'naval', 'land_forces', 'drones'].includes(d.category)).length,
  };

  return {
    totalValueUsd: totalValue,
    totalDeals: activeDealsCount,
    categoriesCount,
  };
}
