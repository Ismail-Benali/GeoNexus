/**
 * دالة مساعدة للحصول على تصريحات قادة دولة معينة
 */
export function getCountryLeadersStatements(countryId) {
  if (!countryId) return [];
  const normalized = countryId.toLowerCase();
  return LEADERS_STATEMENTS_DATABASE.filter(
    (stmt) => stmt.countryId.toLowerCase() === normalized
  );
}

/**
 * دالة إحصائيات عامة لسجل تصريحات القادة
 */
export function getLeadersStatementsStats() {
  const totalStatements = LEADERS_STATEMENTS_DATABASE.length;
  const kingsCount = LEADERS_STATEMENTS_DATABASE.filter((s) => s.leaderType === 'king' || s.leaderType === 'crown_prince').length;
  const presidentsCount = LEADERS_STATEMENTS_DATABASE.filter((s) => s.leaderType === 'president').length;
  const pmCount = LEADERS_STATEMENTS_DATABASE.filter((s) => s.leaderType === 'prime_minister').length;

  return {
    totalStatements,
    kingsCount,
    presidentsCount,
    pmCount,
  };
}
